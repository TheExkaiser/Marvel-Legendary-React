function villainCard(
  slug: string,
  name: string,
  villainGroup: string,
  strength: number,
  vp: number,
  text: string,
  extra: Partial<CardData> = {},
): CardData {
  return {
    id: `villain-${slug}`,
    name,
    img: `/cards/fantastic-four/villain-${slug}.webp`,
    villainGroup,
    strength,
    vp,
    text,
    ...extra,
  }
}

